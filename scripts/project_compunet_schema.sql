CREATE TABLE ROLE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE APP_USER (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    firstName VARCHAR(255) NOT NULL,
    lastName VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    age INTEGER NOT NULL,
    weight NUMERIC(5,2),
    height NUMERIC(5,2)
);

CREATE TABLE USER_ROLE (
    userId INTEGER NOT NULL,
    roleId INTEGER NOT NULL,
    FOREIGN KEY (userId) REFERENCES APP_USER(id) ON DELETE CASCADE,
    FOREIGN KEY (roleId) REFERENCES ROLE(id) ON DELETE CASCADE,
    PRIMARY KEY (userId, roleId)
);

CREATE TABLE PERMISSION (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE ROLE_PERMISSION (
    roleId INTEGER NOT NULL,
    permissionId INTEGER NOT NULL,
    FOREIGN KEY (roleId) REFERENCES ROLE(id) ON DELETE CASCADE,
    FOREIGN KEY (permissionId) REFERENCES PERMISSION(id) ON DELETE CASCADE,
    PRIMARY KEY (roleId, permissionId)
);

CREATE TABLE USER_TRAINER (
    userId INTEGER NOT NULL,
    trainerId INTEGER NOT NULL,
    FOREIGN KEY (userId) REFERENCES APP_USER(id) ON DELETE CASCADE,
    FOREIGN KEY (trainerId) REFERENCES APP_USER(id) ON DELETE CASCADE,
    PRIMARY KEY (userId, trainerId)
);

CREATE TABLE RECOMMENDATION (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    sender INTEGER NOT NULL,
    receiver INTEGER NOT NULL,
    message TEXT NOT NULL,
    date DATE NOT NULL,
    FOREIGN KEY (sender) REFERENCES APP_USER(id) ON DELETE CASCADE,
    FOREIGN KEY (receiver) REFERENCES APP_USER(id) ON DELETE CASCADE
);

CREATE TABLE PHYSICAL_SPACE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    capacity INTEGER NOT NULL
);

CREATE TABLE EVENT (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    date DATE NOT NULL,
    physicalSpace INTEGER NOT NULL,
    description TEXT,
    FOREIGN KEY (physicalSpace) REFERENCES PHYSICAL_SPACE(id) ON DELETE CASCADE
);

CREATE TABLE SUBSCRIPTION (
    userId INTEGER NOT NULL,
    eventId INTEGER NOT NULL,
    attendance BOOLEAN NOT NULL,
    FOREIGN KEY (userId) REFERENCES APP_USER(id) ON DELETE CASCADE,
    FOREIGN KEY (eventId) REFERENCES EVENT(id) ON DELETE CASCADE,
    PRIMARY KEY (userId, eventId)
);

CREATE TABLE DIFFICULTY (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    difficultyName VARCHAR(50) NOT NULL
);

CREATE TABLE TYPE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    typeName VARCHAR(50) NOT NULL
);

CREATE TABLE ROUTINE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    routineName VARCHAR(255) NOT NULL,
    visibility BOOLEAN NOT NULL,
    difficultyId INTEGER NOT NULL,
    typeId INTEGER NOT NULL,
    ownerId INTEGER NOT NULL,
    FOREIGN KEY (ownerId) REFERENCES APP_USER(id) ON DELETE CASCADE,
    FOREIGN KEY (difficultyId) REFERENCES DIFFICULTY(id),
    FOREIGN KEY (typeId) REFERENCES TYPE(id)
);

CREATE TABLE EXERCISE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    exerciseName VARCHAR(255) NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE VISUAL_SUPPORT (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    supportType VARCHAR(10) CHECK (supportType IN ('video','foto')) NOT NULL,
    url VARCHAR(255) NOT NULL,
    exerciseId INTEGER NOT NULL,
    FOREIGN KEY (exerciseId) REFERENCES EXERCISE(id)
);

CREATE TABLE ROUTINE_EXERCISE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    routineId INTEGER NOT NULL,
    exerciseId INTEGER NOT NULL,
    FOREIGN KEY (routineId) REFERENCES ROUTINE(id) ON DELETE CASCADE,
    FOREIGN KEY (exerciseId) REFERENCES EXERCISE(id) ON DELETE CASCADE
);

CREATE TABLE PROGRESS_RECORD (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    routineExercise INTEGER NOT NULL,
    date DATE NOT NULL,
    time TIME NOT NULL,
    progressNotes TEXT,
    series INTEGER NOT NULL,
    repetitions INTEGER NOT NULL,
    weight NUMERIC(5,2) NOT NULL,
    equipment_used VARCHAR(255),
    FOREIGN KEY (routineExercise) REFERENCES ROUTINE_EXERCISE(id) ON DELETE CASCADE
);

